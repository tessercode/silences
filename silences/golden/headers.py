def content(text):
    """C text without comments or whitespace: what the compiler sees, modulo layout."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"\s+", "", text)


def main(argv):
    write, bad = "--write" in argv, 0
    for rel, gen in HEADERS.items():
        path = FIRMWARE / rel
        new = gen()
        same = path.exists() and content(path.read_text()) == content(new)
        bad += not same
        print(f"  {rel:32s} {'matches' if same else 'DIFFERS'}{' (written)' if write else ''}")
        if write:
            path.write_text(new)
    print("every generated header matches the package" if not bad else f"{bad} headers differ")
    return 0 if (write or not bad) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
