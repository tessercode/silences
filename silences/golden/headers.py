"""The firmware's generated headers, regenerated from this package.

    python -m silences.golden.headers            # check every header in the tree against a regeneration
    python -m silences.golden.headers --write    # rewrite them

Every table a board needs (nonlinearity lookup tables, quantized weights, the language-model table,
the Morse decoding tables, the baked test vectors) is computed here from the same code the paper's
evaluation uses, and written as C. The check compares content only (comments and layout ignored).
"""
