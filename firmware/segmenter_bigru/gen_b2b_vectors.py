#!/usr/bin/env python3
"""Bake the golden 0x06 frames into b2b_vectors.h for the BiGRU segmenter's emulator test (both builds share
the inputs; only the expected 0x03 frames differ, and those the comparator reads from the golden).
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(HERE, "..", "golden")


def main():
    m = json.load(open(os.path.join(G, "manifest.json")))
    for fn in ("frames_n1.json", "frames_n5.json"):
        got = hashlib.sha256(open(os.path.join(G, fn), "rb").read()).hexdigest()
        assert got == m["files"][fn], f"golden {fn} sha != manifest -- refuse to bake"
    g1 = json.load(open(os.path.join(G, "frames_n1.json")))
    g5 = json.load(open(os.path.join(G, "frames_n5.json")))
    assert len(g1["vectors"]) == len(g5["vectors"]) == 117

    # the 0x06 must be identical across the two ensembles — assert it rather than assume it
    for a, b in zip(g1["vectors"], g5["vectors"]):
        assert a["vector_id"] == b["vector_id"]
        assert a["expected_0x06_hex"] == b["expected_0x06_hex"], \
            f"vec {a['vector_id']}: 0x06 differs between n1 and n5 — the bake assumption is wrong"

    vecs = g1["vectors"]
    frames = [bytes.fromhex(v["expected_0x06_hex"]) for v in vecs]
    flat = b"".join(frames)
    off, o = [], 0
    for f in frames:
        off.append(o)
        o += len(f)

    L = ["// Generated by gen_b2b_vectors.py from golden/frames_n1.json and frames_n5.json -- do not edit.",
         "// The 117 expected_0x06 frames, byte for byte: the Renode runner feeds these through the",
         "// SHIPPING rx_feed_byte() and the real uart1 TX emits the 0x03 the comparator checks.",
         "#ifndef B2B_VECTORS_H", "#define B2B_VECTORS_H", "#include <stdint.h>", "",
         f"#define B2B_N_VEC {len(vecs)}", f"#define B2B_BYTES_TOTAL {len(flat)}", ""]

    def arr(name, vals, typ, per):
        out = [f"static const {typ} {name}[{len(vals)}] = {{"]
        s = [str(int(v)) for v in vals]
        for i in range(0, len(s), per):
            out.append("    " + ",".join(s[i:i + per]) + ",")
        out.append("};")
        return out

    L += arr("B2B_VID", [v["vector_id"] for v in vecs], "int32_t", 12)
    L += arr("B2B_FLEN", [len(f) for f in frames], "int32_t", 12)
    L += arr("B2B_FOFF", off, "int32_t", 12)
    L += arr("B2B_F06", list(flat), "uint8_t", 24)
    L += ["", "#endif // B2B_VECTORS_H"]
    open(os.path.join(HERE, "b2b_vectors.h"), "w", newline="\n").write("\n".join(L) + "\n")
    print(f"b2b_vectors.h: {len(vecs)} frames, {len(flat)} bytes "
          f"(max frame {max(len(f) for f in frames)} B); 0x06 identical across n1/n5 — asserted")


if __name__ == "__main__":
    main()
