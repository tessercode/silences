#!/usr/bin/env python3
"""Bake the chain golden's encoder inputs (operator, seed, text) from host/cases.txt into e1_vectors.h for the
emulator test.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    p = os.path.join(HERE, "host", "cases.txt")
    with open(p) as f:
        lines = f.read().split("\n")
    n = int(lines[0])
    rows = []
    li = 1
    for _ in range(n):
        hdr = lines[li]
        vid, kind, tag, fist_index, console_fist, seed, ncount = hdr.split(" ", 6)[0:7]
        text = hdr.split("|")[1]
        rows.append((int(vid), int(fist_index), int(seed), text))
        li += 3
    assert len(rows) == n, f"{len(rows)} != {n}"

    out = ["/* AUTO-GENERATED by gen_e1_vectors.py from host/cases.txt -- DO NOT EDIT.",
           " * Emulator test inputs: (fist_index, seed, text) only. The expected ticks/channels",
           " * are deliberately NOT baked -- the device computes them, the host comparator judges.",
           " */",
           "#ifndef E1_VECTORS_H", "#define E1_VECTORS_H", "#include <stdint.h>", "",
           f"#define E1_N_VEC {n}", "",
           "typedef struct { uint16_t vid; uint8_t fist_index; uint64_t seed; const char *text; } e1_vec_t;",
           "", "static const e1_vec_t E1_VEC[E1_N_VEC] = {"]
    for vid, fi, sd, text in rows:
        out.append(f'    {{ {vid}, {fi}, {sd}ull, "{text}" }},')
    out += ["};", "", "#endif /* E1_VECTORS_H */"]
    q = os.path.join(HERE, "e1_vectors.h")
    open(q, "w").write("\n".join(out) + "\n")
    print(f"  wrote {q} ({n} input vectors; NO expected values baked)")


if __name__ == "__main__":
    main()
