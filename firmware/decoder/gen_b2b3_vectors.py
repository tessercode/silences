#!/usr/bin/env python3
"""Bake the decoder test's inputs into b2b3_vectors.h: the golden 0x05 frames (frames_<n>.json), the per-gap
posteriors they carry (segmenter_bigru_<n>.json, beam_cap_vectors.json) and the expected decodes
(beam_<n>.json).  Usage: python gen_b2b3_vectors.py n1|n5
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
B2 = A4 = A2 = os.path.join(HERE, "..", "golden")
VECTORS_H = os.path.join(HERE, "..", "segmenter_bigru", "vectors_3c.h")


def verify(d, files):
    m = json.load(open(os.path.join(d, "manifest.json")))["files"]
    for f in files:
        got = hashlib.sha256(open(os.path.join(d, f), "rb").read()).hexdigest()
        assert got == m[f], f"{d}/{f} sha != manifest — refuse to bake"


def c_arr(name, vals, typ, per=16):
    out = [f"static const {typ} {name}[{max(len(vals),1)}] = {{"]
    s = [str(int(v)) for v in vals] or ["0"]
    for i in range(0, len(s), per):
        out.append("    " + ",".join(s[i:i + per]) + ",")
    out.append("};")
    return out


def c_str_arr(name, strs):
    out = [f"static const char *const {name}[{len(strs)}] = {{"]
    for s in strs:
        esc = s.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{esc}",')
    out.append("};")
    return out


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else "n1"
    verify(B2, [f"frames_{tag}.json"])
    verify(A4, [f"beam_{tag}.json", "beam_cap_vectors.json"])
    verify(A2, [f"segmenter_bigru_{tag}.json"])

    b2 = json.load(open(os.path.join(B2, f"frames_{tag}.json")))["vectors"]
    a4 = {int(v["vector_id"]): v
          for v in json.load(open(os.path.join(A4, f"beam_{tag}.json")))["vectors"]}
    a2r = {int(v["vector_id"]): v
           for v in json.load(open(os.path.join(A2, f"segmenter_bigru_{tag}.json")))["vectors"]}
    cap = json.load(open(os.path.join(A4, "beam_cap_vectors.json")))["vectors"]
    cap_lp3 = {int(v["vid"]): v[f"lp3_{tag}"] for v in cap}
    cap_ch = {int(v["vid"]): v["ch"] for v in cap}

    # the 47+50 A2 vectors' ch[] come from vectors_3c.h's flat arrays
    txt = open(VECTORS_H).read()

    def arr(name):
        m = re.search(name + r"\[\d+\] = \{(.*?)\};", txt, re.S)
        return [int(t) for t in m.group(1).replace("\n", " ").split(",") if t.strip()]

    vid_h, nsp_h, off_h, ch_h = arr("VEC3_ID"), arr("VEC3_NSPIKE"), arr("VEC3_OFFSET"), arr("SPIKE3_CH")
    a2_ch = {vid_h[i]: ch_h[off_h[i]:off_h[i] + nsp_h[i]] for i in range(len(vid_h))}

    f05, exp_text, exp_seg, exp_score, exp_died, vids, nsps, ngs = [], [], [], [], [], [], [], []
    ref_lp3, ref_ch = [], []
    for v in b2:
        vid = int(v["vector_id"])
        f05.append(bytes.fromhex(v["expected_0x05_hex"]))
        vids.append(vid); nsps.append(v["n_spikes"]); ngs.append(v["n_gaps"])
        g = a4[vid]
        exp_died.append(1 if g["beam_died"] else 0)
        exp_text.append(g["decoded_text"] or "")
        exp_seg.append("".join(str(x) for x in (g["seg"] or [])))
        exp_score.append(g["final_score_q16"] if g["final_score_q16"] is not None else 0)
        # the parse truth
        lp3 = a2r[vid]["log_p3_q16"] if vid in a2r else cap_lp3[vid]
        ch = a2_ch[vid] if vid in a2_ch else cap_ch[vid]
        assert len(lp3) == v["n_gaps"] and len(ch) == v["n_spikes"], f"vec {vid}: frozen shape drift"
        ref_lp3.append([x for row in lp3 for x in row])
        ref_ch.append(list(ch))

    # ---- cross-check: the baked parse truth must already be inside the golden 0x05 frames ----
    for i, v in enumerate(b2):
        pl = f05[i][5:-1]
        n = (pl[3] << 8) | pl[4]
        ch_in_frame = list(pl[5:5 + n])
        assert ch_in_frame == ref_ch[i], f"vec {vids[i]}: baked ch != the 0x05's ch"
        o = 5 + n
        lp_in_frame = [int.from_bytes(pl[o + 4 * t:o + 4 * t + 4], "big", signed=True)
                       for t in range((n - 1) * 3)]
        assert lp_in_frame == ref_lp3[i], f"vec {vids[i]}: baked lp3 != the 0x05's lp3"
    print(f"cross-check: the baked parse truth is byte-identical to what the golden 0x05 frames carry "
          f"({len(b2)}/117) — L1 cannot pass vacuously")

    flat5 = b"".join(f05)
    off5, o = [], 0
    for f in f05:
        off5.append(o); o += len(f)
    flat_lp3 = [x for r in ref_lp3 for x in r]
    offl, o = [], 0
    for r in ref_lp3:
        offl.append(o); o += len(r)
    flat_ch = [x for r in ref_ch for x in r]
    offc, o = [], 0
    for r in ref_ch:
        offc.append(o); o += len(r)

    L = [f"// Generated by gen_b2b3_vectors.py from the frame, segmenter and beam goldens ({tag}) -- do not edit.",
         "// the golden 0x05 frames in; their channels and posteriors = the parse truth;",
         "// A4's decoded_text/seg/score = the L2 decode truth. Nothing here defines truth.",
         "#ifndef B2B3_VECTORS_H", "#define B2B3_VECTORS_H", "#include <stdint.h>", "",
         f"#define B3_N_VEC {len(b2)}", f"#define B3_NSEEDS {1 if tag == 'n1' else 5}", ""]
    L += c_arr("B3_VID", vids, "int32_t", 12)
    L += c_arr("B3_NSPIKES", nsps, "int32_t", 12)
    L += c_arr("B3_NGAPS", ngs, "int32_t", 12)
    L += c_arr("B3_F05_LEN", [len(x) for x in f05], "int32_t", 12)
    L += c_arr("B3_F05_OFF", off5, "int32_t", 12)
    L += c_arr("B3_F05", list(flat5), "uint8_t", 24)
    L += c_arr("B3_REF_CH_OFF", offc, "int32_t", 12)
    L += c_arr("B3_REF_CH", flat_ch, "uint8_t", 24)
    L += c_arr("B3_REF_LP3_OFF", offl, "int32_t", 12)
    L += c_arr("B3_REF_LP3", flat_lp3, "int32_t", 8)
    L += c_arr("B3_DIED", exp_died, "uint8_t", 24)
    L += c_str_arr("B3_TEXT", exp_text)
    L += c_str_arr("B3_SEG", exp_seg)
    L += ["static const int64_t B3_SCORE[%d] = {" % len(exp_score)]
    for i in range(0, len(exp_score), 6):
        L.append("    " + ",".join(f"{int(x)}LL" for x in exp_score[i:i + 6]) + ",")
    L.append("};")
    L += ["", "#endif // B2B3_VECTORS_H"]
    open(os.path.join(HERE, "b2b3_vectors.h"), "w", newline="\n").write("\n".join(L) + "\n")
    print(f"b2b3_vectors.h [{tag}]: {len(b2)} vectors, 0x05 {len(flat5)} B, "
          f"lp3 {len(flat_lp3)} ints, {sum(exp_died)} beam death(s)")


if __name__ == "__main__":
    main()
