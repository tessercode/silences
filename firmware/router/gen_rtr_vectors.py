#!/usr/bin/env python3
"""Bake the golden (0x06, 0x03) frame pairs into rtr_vectors.h for the router's emulator test.
Usage: python gen_rtr_vectors.py n1|n5
"""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(HERE, "..", "golden")

def arr(name, vals, typ, per):
    out = [f"static const {typ} {name}[{len(vals)}] = {{"]
    s = [str(int(v)) for v in vals]
    for i in range(0, len(s), per):
        out.append("    " + ",".join(s[i:i + per]) + ",")
    out.append("};")
    return out

def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else "n1"
    fn = f"frames_{tag}.json"
    m = json.load(open(os.path.join(G, "manifest.json")))
    got = hashlib.sha256(open(os.path.join(G, fn), "rb").read()).hexdigest()
    assert got == m["files"][fn], f"golden {fn} sha != manifest -- refuse to bake"
    g = json.load(open(os.path.join(G, fn)))
    vecs = g["vectors"]
    assert len(vecs) == 117

    f06 = [bytes.fromhex(v["expected_0x06_hex"]) for v in vecs]
    f03 = [bytes.fromhex(v["expected_0x03_hex"]) for v in vecs]
    flat6, flat3 = b"".join(f06), b"".join(f03)
    off6, off3, o6, o3 = [], [], 0, 0
    for a, b in zip(f06, f03):
        off6.append(o6); o6 += len(a)
        off3.append(o3); o3 += len(b)

    L = [f"// Generated by gen_rtr_vectors.py from golden/{fn} -- do not edit.",
         "// The 117 (expected_0x06, expected_0x03) input pairs; the runner feeds them INTERLEAVED",
         "// through the SHIPPING core and the real TX emits the 0x05 the comparator checks.",
         "#ifndef RTR_VECTORS_H", "#define RTR_VECTORS_H", "#include <stdint.h>", "",
         f"#define RTR_N_VEC {len(vecs)}", f"#define RTR_NSEEDS {g['n_seeds']}", ""]
    L += arr("RTR_VID", [v["vector_id"] for v in vecs], "int32_t", 12)
    L += arr("RTR_F06_LEN", [len(x) for x in f06], "int32_t", 12)
    L += arr("RTR_F06_OFF", off6, "int32_t", 12)
    L += arr("RTR_F03_LEN", [len(x) for x in f03], "int32_t", 12)
    L += arr("RTR_F03_OFF", off3, "int32_t", 12)
    L += arr("RTR_F06", list(flat6), "uint8_t", 24)
    L += arr("RTR_F03", list(flat3), "uint8_t", 24)
    L += ["", "#endif // RTR_VECTORS_H"]
    open(os.path.join(HERE, "rtr_vectors.h"), "w", newline="\n").write("\n".join(L) + "\n")
    print(f"rtr_vectors.h [{tag}]: 117 pairs, 0x06 {len(flat6)} B + 0x03 {len(flat3)} B = "
          f"{len(flat6)+len(flat3)} B baked")

if __name__ == "__main__":
    main()
